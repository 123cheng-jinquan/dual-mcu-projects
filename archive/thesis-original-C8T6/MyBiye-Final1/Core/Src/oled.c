static void OLED_WriteCommand(uint8_t cmd)
{
    uint8_t data[2];
    data[0] = 0x00;
    data[1] = cmd;
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, data, 2, 100);
}

static void OLED_WriteData(uint8_t *data, uint16_t size)
{
    uint8_t buf[17];
    uint16_t offset = 0;
    uint8_t chunk;

    while (offset < size)
    {
        chunk = (size - offset > 16U) ? 16U : (uint8_t)(size - offset);
        buf[0] = 0x40;
        memcpy(&buf[1], &data[offset], chunk);
        HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, chunk + 1U, 100);
        offset += chunk;
    }
}

void OLED_SetCursor(uint8_t page, uint8_t column)
{
    OLED_WriteCommand(0xB0 + page);
    OLED_WriteCommand(0x10 | ((column & 0xF0) >> 4));
    OLED_WriteCommand(0x00 | (column & 0x0F));
}

void OLED_Refresh(void)
{
    uint8_t page;
    for (page = 0; page < OLED_PAGES; page++)
    {
        OLED_SetCursor(page, 0);
        OLED_WriteData(OLED_GRAM[page], OLED_WIDTH);
    }
}

void OLED_Clear(void)
{
    memset(OLED_GRAM, 0x00, sizeof(OLED_GRAM));
    OLED_Refresh();
}

void OLED_ShowChar(uint8_t page, uint8_t column, char chr)
{
    uint8_t index;
    if (chr < 32 || chr > 126)
    {
        chr = '?';
    }
    index = (uint8_t)(chr - 32);

    if (page >= OLED_PAGES || column > OLED_WIDTH - 6)
    {
        return;
    }

    memcpy(&OLED_GRAM[page][column], OLED_Font6x8[index], 6);
}

void OLED_ShowString(uint8_t page, uint8_t column, const char *str)
{
    while (*str != '\0')
    {
        if (column > OLED_WIDTH - 6)
        {
            column = 0;
            page++;
        }
        if (page >= OLED_PAGES)
        {
            break;
        }
        OLED_ShowChar(page, column, *str++);
        column += 6;
    }
    OLED_Refresh();
}

void OLED_ShowNum(uint8_t page, uint8_t column, uint32_t num, uint8_t len)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%*lu", len, (unsigned long)num);
    OLED_ShowString(page, column, buf);
}

