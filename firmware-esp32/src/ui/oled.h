#pragma once
/* =============================================================================
 *  oled.h — SSD1306 128×64 I2C 本地显示（gui.cpp 的"路径 C"）
 * =============================================================================
 *  定位（为什么不直接走 LVGL）：
 *    · LVGL 那条路要求先确定屏驱动 IC / 分辨率 / 触摸（config.h 的 [TBD-1]），
 *      在屏到手之前一行数据都看不到；
 *    · SSD1306 是**协议固定**的：I2C + 一组固定命令字，与屏型号无关。
 *      所以它能立刻把"分类结果 / 振动 std / 485 在线状态"显示出来，
 *      并且天然与 LVGL 解耦 —— 两条显示通道，任意一条挂掉另一条照跑。
 *
 *  ★硬约束（和 modbus_master.h 顶上那条一样重要）★
 *    本模块**只读**共享数据，绝不向总线发请求：
 *      · 慢车道快照   ← slow_get_latest()（seqlock，无锁）
 *      · 窗口 std      ← oled_set_vibration()（由 GUI 任务在收到窗口时算好填入）
 *      · 推理结果      ← infer_get_latest()（临界区拷贝）
 *      · 总线统计/在线 ← mb_get_stats() / oled_set_online()（临界区拷贝）
 *    因此：OLED 未接、I2C 被拉死、SSD1306 损坏，都**不会**影响 Modbus 轮询。
 *
 *  线程模型：
 *    oled_init()/oled_bind() 在 setup() 里（单线程）调用；
 *    写侧（oled_set_*）由 task_modbus_bus / task_gui 调，内部用临界区保护；
 *    读+刷屏由 task_oled 独占（也是唯一碰 I2C 的任务）。
 * ============================================================================= */

#include <Arduino.h>
#include <stdint.h>
#include <stdbool.h>

#include "config.h"
#include "modbus_master.h"
#include "app_tasks.h"

/* -----------------------------------------------------------------------------
 * 初始化 I2C 并探测 SSD1306。
 * 返回 true = 屏在线且已初始化（此后 task_oled 会定期刷屏）。
 * 返回 false = 没插屏/地址不对/总线故障 —— **不是致命错误**：
 *              总线、GUI、网络照跑，task_oled 会每隔 OLED_RETRY_PERIOD_MS 重试一次
 *              （所以支持"运行时再插上屏"）。
 * 在 setup() 里调用（早于任何任务）——I2C 总线初始化必须单线程完成。
 * -------------------------------------------------------------------------- */
bool oled_init(void);

/* 创建 task_oled（core0 / TASK_PRIO_OLED）。由 app_tasks_start() 调用。
 * 返回 false = 任务创建失败（内存不足）。 */
bool oled_task_start(void);

/* 任务入口（由 app_tasks_start() 创建，不要手动调）。 */
void task_oled(void *arg);

/* -----------------------------------------------------------------------------
 * 写侧接口（供其它任务更新"要显示的东西"）
 * -------------------------------------------------------------------------- */

/* 485 在线状态：由 task_modbus_bus 在状态翻转时调用（也可以每轮都调，代价很小）。 */
void oled_set_online(bool online);

/* 振动强度：由 GUI 任务收到新窗口（UI_MSG_WINDOW）时算好填入。
 *   std_raw  = 三轴加速度 std 的最大值（MPU6050 原始 LSB，静止约 20~60）
 *   pp_raw   = 三轴加速度峰峰值的最大值（同一个窗口，用于区分"抖动"和"大幅度摆动"）
 *   seq      = 该窗口的窗口序号（0x0101）
 * 为什么不在这里自己算：算 std 要遍历 100×6 个样本，属于"窗口的消费者"该干的活，
 * 让显示模块去遍历会把它和 GUI 的职责搅在一起。 */
void oled_set_vibration(uint16_t std_raw, uint16_t pp_raw, uint16_t seq);

/* -----------------------------------------------------------------------------
 * 便捷函数：给 GUI 用。把"最新状态"重画一遍（GUI 每 GUI_DIAG_REFRESH_MS 调用）。
 * 其实刷屏由 task_oled 自己做，这个函数只用来**同步在线标志**，
 * 保留它是为了让 gui_set_online() 有个明确的落点（见 gui.cpp）。
 * -------------------------------------------------------------------------- */
void oled_on_online_event(bool online);

/* -----------------------------------------------------------------------------
 * 诊断：最近一次刷屏的写入字节数 / 错误计数（打日志用）。
 * -------------------------------------------------------------------------- */
uint32_t oled_error_count(void);
