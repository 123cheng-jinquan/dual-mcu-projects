/* =============================================================================
 *  speaker.h — 声纹注册 / 验证（说话人确认）
 * =============================================================================
 *  任务定义（这是"说话人确认"Speaker Verification，不是"说话人辨认"）
 *  ---------------------------------------------------------------------------
 *    给了用户的一段语音 → 判断"是不是已注册的那个人" → PASS / FAIL
 *
 *  算法选择：**模板匹配（template matching）+ 余弦相似度**
 *  ---------------------------------------------------------------------------
 *  为什么不用神经网络（如 x-vector / ECAPA-TDNN）：
 *    · 那些模型要几万条多人语音训练，**7 天内做不出来**（也没有数据）
 *    · 模板匹配是声纹识别的**经典做法**（i-vector 之前的主流），
 *      只需要用户录几段语音注册，**当天就能跑通、能演示、能讲清楚**
 *    · 面试时可以讲"为什么在小样本场景下选模板匹配而不是深度模型"——
 *      这本身就是个不错的工程判断点
 *
 *  ★ 相似度度量的关键改进（踩过的坑）★
 *  ---------------------------------------------------------------------------
 *  最初直接用**原始 MFCC 向量**算余弦相似度，自检发现：
 *      300Hz 和 800Hz 两段完全不同的信号，相似度竟然有 0.73！
 *  原因：MFCC 各维的**数值范围差异极大**
 *      · 第 0 维（对数能量）：几十 ~ 上百
 *      · 高阶倒谱系数：      零点几 ~ 几
 *      余弦相似度本质是"方向"，但数值大的维度会**压倒性主导**结果。
 *      ⇒ 两段完全不同的声音，只要"能量差不多"就得到很高的相似度。
 *
 *  修正：**每一维分别标准化（z-score）后再算余弦**
 *      · 用注册时多段样本的**均值和标准差**做标准化
 *      · 这样每一维都变成"相对于本人平均值的偏离程度（多少个标准差）"，
 *        量纲统一，高阶系数的区分能力才发挥出来
 *      · 同时给低阶倒谱系数（更稳定、更代表音色）更高的权重
 *
 *  这个"发现问题 → 定位原因 → 改进度量"的过程，本身就是很好的工程案例。
 * ========================================================================== */

#ifndef __SPEAKER_H
#define __SPEAKER_H

#include <Arduino.h>
#include "mfcc.h"

/* ---- 配置 -------------------------------------------------------------- */
#define SPK_MAX_TEMPLATES   5      /* 最多注册几段（多段可以提升鲁棒性）*/
#define SPK_MIN_TEMPLATES   2      /* 至少要有几段才能启用验证 */

/* 判定阈值：标准化后的余弦相似度，超过才算同一个人。
 * ⚠ 这个值**必须用真实语音实测标定** —— 不同人/不同麦克风距离下差别很大。
 *   先用一个保守默认值，跑 '  ' 命令看实际分布再调。 */
#define SPK_THRESHOLD_DEF   0.62f

/* ---- 状态 -------------------------------------------------------------- */
struct SpkState {
    bool     enrolled;                 /* 是否已注册 */
    uint8_t  count;                    /* 已注册段数 */
    float    mean[MFCC_FEAT_DIM];      /* 各维均值（标准化用）*/
    float    std[MFCC_FEAT_DIM];       /* 各维标准差（标准化用）*/
    float    feats[SPK_MAX_TEMPLATES][MFCC_FEAT_DIM];  /* 原始模板 */
    float    threshold;
    float    sigma2;                   /* 距離尺度（注册后自动标定）*/
    uint32_t magic;                    /* 结构体版本标识，防止 NVS 数据不兼容 */
};

/* 结构体版本：改了 SpkState 的布局（比如特征维度变化）就要改这个数，
 * 这样载入旧数据时会因 magic 不匹配而自动忽略，避免读到脏数据。 */
#define SPK_STATE_MAGIC   0x564C4B05UL   /* "VLK" + 版本号 5 */

/* ---- API --------------------------------------------------------------- */

/** 初始化（从 NVS 载入已保存的模板，如果有）。 */
void spkBegin(void);

/** 注册：把一段 MFCC 特征加入模板库。返回 true = 成功。 */
bool spkEnroll(const float *feat);

/** 验证：把一段 MFCC 特征与模板比对。
 *  返回标准化余弦相似度（-1 ~ 1）。第三个参数可选返回"是否通过"。 */
float spkVerify(const float *feat, bool *pass);

/** 当前状态（只读）。 */
const SpkState &spkState(void);

/** 清空模板（重新注册）。 */
void spkClear(void);

/** 把模板保存到 NVS / 从 NVS 载入。 */
bool spkSave(void);
bool spkLoad(void);

/** 打印当前模板信息（调试用）。 */
void spkDump(void);

/** 用**已注册的模板互相验证**，打印相似度矩阵。
 *  这是**阈值标定**的关键工具：同一人的自相似度应该在 0.8 以上，
 *  不同人应该明显低。看这个分布才能定出合理的阈值。 */
void spkCrossCheck(void);

#endif /* __SPEAKER_H */
