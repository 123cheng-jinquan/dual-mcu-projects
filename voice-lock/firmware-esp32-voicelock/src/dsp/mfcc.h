/* =============================================================================
 *  mfcc.h — MFCC 特征提取（Mel 频率倒谱系数）
 * =============================================================================
 *  为什么用 MFCC 做声纹
 *  ---------------------------------------------------------------------------
 *  MFCC 的设计初衷是"模拟人耳对频率的非线性感知"：
 *    · 人耳对**低频**的分辨能力远强于高频（mel 刻度就是描述这个的）
 *    · 语音的"音色"（区分谁在说话）主要体现在**频谱包络**上，
 *      而频谱包络 = 对数幅度谱做 DCT 后的**低频部分**
 *  ⇒ 取 DCT 的前 13 个系数，就抓住了"音色"的主要信息，
 *    同时丢掉了基频（音高）的细节 —— 这正是声纹识别想要的：
 *    **同一个人说不同内容，MFCC 依然相似；不同人说同样内容，MFCC 差别明显。**
 *
 *  处理流程（标准 MFCC，和教科书一致）
 *  ---------------------------------------------------------------------------
 *    ① 预加重 (pre-emphasis)  y[n] = x[n] - 0.97·x[n-1]
 *       提升高频，补偿语音在发声中 ~6dB/oct 的高频衰减
 *    ② 分帧 (framing)        25ms 帧长 / 10ms 帧移
 *       语音是短时平稳的，所以要切成小段分别分析
 *    ③ 加窗 (windowing)      Hamming 窗
 *       减少帧边缘的截断效应（频谱泄漏）
 *    ④ FFT                   把时域转成频域，得到幅度谱
 *    ⑤ Mel 滤波器组          把线性频率映射到 mel 刻度，得到 26 个频带能量
 *    ⑥ 取对数                log(能量)
 *    ⑦ DCT                   把 26 个对数能量压缩成 13 个倒谱系数
 *    ⑧ 一阶差分 (delta)      描述特征随时间的变化，能显著提升识别率
 *
 *  本实现的特点
 *  ---------------------------------------------------------------------------
 *  · **纯整数/定点**：Cortex-M3 无 FPU，ESP32 虽然有 FPU 但浮点也慢。
 *    FFT 用的是 **Q15 定点基-2 FFT**（2048 点以内）。
 *  · **自己实现 FFT**：不依赖外部库，代码可控、便于讲解。
 *  · **内存友好**：滤波器组和窗函数都是**运行时算一次**存在静态数组里。
 *
 *  ⚠ 关于采样率：F103 侧是 8000Hz，所以奈奎斯特上限 4000Hz。
 *    MFCC 的 mel 滤波器组按 0~4000Hz 布置，这是电话语音的经典配置，
 *    对声纹识别是够用的（虽然比 16kHz 少了些高频细节）。
 * ========================================================================== */

#ifndef __MFCC_H
#define __MFCC_H

#include <Arduino.h>

/* ---- 参数 -------------------------------------------------------------- */
#define MFCC_SAMPLE_RATE     8000      /* 与 F103 侧一致 */
#define MFCC_FRAME_LEN_MS    25        /* 帧长 25ms */
#define MFCC_FRAME_STEP_MS   10        /* 帧移 10ms */
#define MFCC_FRAME_LEN       ((MFCC_SAMPLE_RATE / 1000) * MFCC_FRAME_LEN_MS)  /* 200 点 */
#define MFCC_FRAME_STEP      ((MFCC_SAMPLE_RATE / 1000) * MFCC_FRAME_STEP_MS) /* 80 点 */
#define MFCC_FFT_SIZE        256       /* >= FRAME_LEN，取 2 的幂方便基-2 FFT */
#define MFCC_MEL_BANDS       26        /* mel 滤波器个数 */
#define MFCC_NUM_CEPS        13        /* 保留的倒谱系数个数 */
#define MFCC_PREEMPH         0.97f     /* 预加重系数 */

/* 一帧的静态特征维度：13 个 MFCC + 1 个对数能量 = 14 */
#define MFCC_STATIC_DIM      (MFCC_NUM_CEPS + 1)

/* 动态维度 = 静态 + Δ + ΔΔ（每个 14 维），共 42 */
#define MFCC_DYN_DIM         (MFCC_STATIC_DIM * 3)

/* ★★ 最终特征维度 = 42 维的「均值」+ 42 维的「标准差」= 84 维 ★★
 *
 *  为什么从"帧平均"改成"均值+标准差"（这是改到第 4 版才对的）
 *  ---------------------------------------------------------------------------
 *  走过的弯路：
 *    v1 原始 MFCC 帧平均 + 余弦 → 被能量维主导，不同信号相似度 0.73
 *    v2 对每维 z-score 后再余弦   → **自己的录音之间相似度变成 -0.8**（更糟）
 *    v3 加权 + L2 归一（不减均值）→ 本人 0.99，但**放别人说话的视频也 0.994**
 *    v4 加 CMN + Δ/ΔΔ            → 交叉检查又变负（-0.76）
 *
 *  v4 失败的根因（很关键）：
 *    CMN 会把**每一维在整段语音上的均值减成 0**。
 *    这样一来，"对所有帧求平均"得到的向量**几乎全是 0**
 *    —— 剩下的只是浮点舍入噪声。拿噪声向量算余弦，方向随机 ⇒ 出现负值。
 *    ⇒ **"帧平均"这个操作和 CMN 是互斥的**：CMN 之后必须看"分布"而不是"平均"。
 *
 *  v5（现在）：特征 = **每维的均值 + 每维的标准差**（各 42 维，共 84 维）
 *    · 均值   ：描述"这段语音的频谱包络平均长什么样"   ⇒ 音色
 *    · 标准差 ：描述"包络起伏有多大、变化多剧烈"       ⇒ 发音动态
 *    两者一起，才是对"这段语音"的完整统计描述。
 *    因为标准差包含幅度信息（不是纯方向），所以**距离度量改用归一化欧氏距离**，
 *    不再用余弦 —— 余弦只看方向，会丢掉"幅度"这个有效信息。
 * ========================================================================== */
#define MFCC_FEAT_DIM        (MFCC_DYN_DIM * 2)

/** 从一段音频提取特征：42 维动态 MFCC 的均值 + 标准差 = 84 维。
 *
 *  samples : 8bit 量化样本（0~255），来自 F103
 *  count   : 样本个数
 *  out     : 输出，长度 MFCC_FEAT_DIM
 *  返回     : 实际用于统计的帧数（0 表示失败） */
int mfccCompute(const uint8_t *samples, uint32_t count, float *out);

/** 取上一步每个维度的标准差（可选，用于自适应加权）。
 *  只在 mfccCompute 之后调用有效。 */
const float *mfccLastStd(void);

/** 计算两个特征向量的余弦相似度（-1 ~ 1，越大越像）。
 *  为什么用余弦而不是欧氏距离：
 *    余弦只看"方向"，对整体幅度的缩放不敏感 —— 而说话音量大小、
 *    离麦克风远近都会影响幅度，不应该影响"是不是同一个人"的判断。 */
float mfccCosine(const float *a, const float *b, int dim);

/** 把特征向量归一化成单位长度（余弦相似度前建议先做）。
 *  原地修改。 */
void mfccNormalize(float *v, int dim);

/* ---- 自检（'m' 命令用）------------------------------------------------- */
/** 用合成信号（正弦+噪声）跑一遍完整流程，打印中间结果，验证实现正确。
 *  这是个"离线单元测试"，不需要真实音频也能确认算法没写错。 */
void mfccSelfTest(void);

#endif /* __MFCC_H */
